#!/usr/bin/env python3
"""
创建 v2.50.2 框架：将负面模式嵌入评分锚定规则

v2.50.1 的问题：
- 前置扣分指令在分析框架和结论维度被忽略
- 原因：prompt 太长（>2000字），AI 按后面的详细评分标准给分

v2.50.2 的策略：
- 不再使用独立的"扣分步骤"
- 直接在评分锚定表中嵌入负面模式的降档条件
- AI 在按步骤评分时自然考虑负面模式

具体做法：
- 在"第一步"的评分标准中增加负面模式检测
- 在评分锚定表中增加"负面模式触发时强制降档"规则
- 保留问题创新性的前置扣分（已验证有效）
"""
import yaml
from pathlib import Path

# 问题创新性：保留前置扣分（已验证有效）
PROBLEM_ORIGINALITY_PREFIX = """【强制前置检查 - 负面模式扣分】

⚠️ 在进行任何评分之前，必须先完成以下负面模式检查。如果跳过此步骤，后续评分无效。

请逐项检查并记录扣分：

□ 检查1：新概念包装旧问题（扣 15-25 分）
  条件：论文引入新概念/新术语作为核心创新点，但未明确说明新概念相对既有概念的理论进步
  判断方法：新概念是否只是用新词描述已有讨论？是否说明了解释力提升？
  - 未说明任何优势 → 扣 25 分
  - 只说"填补空白"但未说明解释力提升 → 扣 20 分
  - 有部分说明但不充分 → 扣 15 分
  - 不满足条件 → 不扣分

□ 检查2：宏观介绍非深度分析（扣 15-20 分）
  条件：论文完成了体系介绍但未触及现实问题，无不同学者观点的交锋
  判断方法：全文是否有学者观点交锋？是否只是系统归纳既定立场？
  - 全文无任何学者观点交锋 → 扣 20 分
  - 有提及分歧但未展开 → 扣 15 分
  - 不满足条件 → 不扣分

□ 检查3：主题声明非研究问题（扣 20-30 分）
  条件：全文主要是阐释既定立场，无可争辩的法学争点
  判断方法：能否找到"XX是否YY""如何ZZ"等问题句？还是只有主题声明？
  - 全文无任何问题句，只有主题声明 → 扣 30 分
  - 有问题句但实质是政策倡导 → 扣 20 分
  - 不满足条件 → 不扣分

扣分合计 = ___分（记录在 score_rationale 中）
扣分后的分数不得低于 30 分。

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
现在开始正式评分（最终分数 = 正式评分 - 扣分合计）：
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

"""

# 分析框架：嵌入评分步骤的负面模式检测
AF_STEP1_INJECTION = """

【负面模式降档规则 - 与可操作性检查同步执行】：
在完成上述4项标准检查后，必须同步检查以下负面模式。如果触发，强制降档：

A. 口号式呼吁：统计论文中"应当""必须""需要完善""需要加强"等规范性表述的数量。
   如果≥5处且对应的具体制度方案不足（每个"应当"后无具体法条/程序/规则），
   则框架可操作性得分最高为2（无论上面4项标准满足多少）。

B. 概念堆砌：检查论文核心术语（≥3个）是否每个都有"本文所称XX是指..."的明确定义。
   如果≥2个核心术语无明确定义，
   则框架可操作性得分最高为1（无论上面4项标准满足多少）。

C. 宏观介绍非深度分析：检查论文是否只完成体系介绍而未触及具体问题。
   如果全文无任何具体问题的深入分析（只有宏观框架描述），
   则框架可操作性得分最高为2。

框架可操作性得分 = min(满足的标准数量, 负面模式上限)

"""

# 结论可接受性：嵌入评分步骤的负面模式检测
CC_STEP_INJECTION = """

【负面模式降档规则 - 与对话度/制度度检查同步执行】：
在完成上述标准检查后，必须同步检查以下负面模式。如果触发，强制降档：

A. 生搬硬套：检查结论是否采用"立法-司法-执法-守法"或类似机械四分法。
   如果采用机械框架且每个方面都无具体论证（只有空泛表述），
   则共同体对话度得分最高为1（因为机械套用无法被学界认真回应）。

B. 万能药式对策：检查对策建议是否全部停留在"完善立法、加强监管、健全机制"层面。
   如果对策≥3条且全部为空泛表述（无具体法条/程序/规则），
   则制度可接受度得分最高为1。

C. 结论不足以支撑主张：检查论文是否提出新理论作为替代方案但未说明优势。
   如果新理论未明确说明相对既有理论的优势，
   则共同体对话度得分最高为2。

"""


def apply_v2_50_2_rules():
    """创建 v2.50.2 框架"""

    source_path = Path("configs/frameworks/law-v2.47-20260511.yaml")
    target_path = Path("configs/frameworks/law-v2.50.2-20260514.yaml")

    with open(source_path, 'r', encoding='utf-8') as f:
        config = yaml.safe_load(f)

    # 1. 更新 metadata
    config['metadata']['name'] = "法学评价框架 v2.50.2（负面模式嵌入评分锚定）"
    config['metadata']['version'] = "2.50.2"
    config['metadata']['created'] = "2026-05-14"
    config['metadata']['previous_version'] = "2.50.1"
    config['metadata']['source'] = "v2.47 + 负面模式嵌入评分锚定"
    config['metadata']['changelog'] = """v2.50.2 变化（2026-05-14，负面模式嵌入评分锚定）：
【目标】修复 v2.50.1 中分析框架和结论维度扣分指令被忽略的问题。

核心变化：
1. 问题创新性：保留前置扣分（v2.50.1 已验证有效）
2. 分析框架：将负面模式检测嵌入"第一步：框架可操作性检查"的评分流程中
3. 结论可接受性：将负面模式检测嵌入"轨道A/B"的评分流程中
4. 不再使用独立的"扣分步骤"，而是直接限制子项得分上限

设计原理：
- v2.50.1 证明：独立的前置扣分在长 prompt 中会被后续评分标准覆盖
- 新策略：将负面模式检测嵌入评分步骤本身，AI 在逐项评分时自然考虑
- 使用"子项得分上限"而非"总分扣分"，更难被忽略

预期改进：
- 分析框架维度：邵莉莉 < 65、崔聪聪 < 60、包晓丽 < 70
- 结论可接受性维度：杨清望 < 60（生搬硬套）"""

    # 2. 修改 prompt_template
    dimensions = config['dimensions']

    for dim in dimensions:
        if dim['key'] == 'problem_originality':
            # 保留前置扣分（已验证有效）
            dim['prompt_template'] = PROBLEM_ORIGINALITY_PREFIX + dim['prompt_template']
            print(f"  ✅ 问题创新性：保留前置扣分")

        elif dim['key'] == 'analytical_framework':
            pt = dim['prompt_template']
            # 在"框架可操作性得分 = 满足的标准数量（0-4分）"之前插入
            marker = "框架可操作性得分 = 满足的标准数量"
            if marker in pt:
                pt = pt.replace(marker, AF_STEP1_INJECTION.strip() + "\n\n" + marker)
                dim['prompt_template'] = pt
                print(f"  ✅ 分析框架：负面模式嵌入可操作性检查")
            else:
                print(f"  ⚠️ 分析框架：未找到插入标记，追加到末尾")
                dim['prompt_template'] = pt + AF_STEP1_INJECTION

        elif dim['key'] == 'conclusion_consensus':
            pt = dim['prompt_template']
            # 在"共同体对话度得分 = 满足的标准数量"之前插入
            marker = "共同体对话度得分 = 满足的标准数量"
            if marker in pt:
                pt = pt.replace(marker, CC_STEP_INJECTION.strip() + "\n\n" + marker)
                dim['prompt_template'] = pt
                print(f"  ✅ 结论可接受性：负面模式嵌入对话度检查")
            else:
                print(f"  ⚠️ 结论可接受性：未找到插入标记，追加到末尾")
                dim['prompt_template'] = pt + CC_STEP_INJECTION

    # 3. 保存
    with open(target_path, 'w', encoding='utf-8') as f:
        yaml.dump(config, f, allow_unicode=True, default_flow_style=False, sort_keys=False, width=1000)

    print(f"\n✅ 已生成 {target_path}")


if __name__ == "__main__":
    apply_v2_50_2_rules()
