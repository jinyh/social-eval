def apply_v2_50_1_rules():
    """创建 v2.50.1 框架：扣分指令前置"""

    source_path = Path("configs/frameworks/law-v2.47-20260511.yaml")
    target_path = Path("configs/frameworks/law-v2.50.1-20260514.yaml")

    with open(source_path, 'r', encoding='utf-8') as f:
        config = yaml.safe_load(f)

    # 1. 更新 metadata
    config['metadata']['name'] = "法学评价框架 v2.50.1（扣分指令前置）"
    config['metadata']['version'] = "2.50.1"
    config['metadata']['created'] = "2026-05-14"
    config['metadata']['previous_version'] = "2.50.0"
    config['metadata']['source'] = "v2.47 + 扣分指令前置"
    config['metadata']['changelog'] = """v2.50.1 变化（2026-05-14，扣分指令前置）：
【目标】修复 v2.50 中扣分指令被淹没的问题。

核心变化：
1. 将扣分指令从 prompt 中间移到最前面（"第一步"之前）
2. 增加"先扣分后评分"的强制流程
3. 强化措辞："如果跳过此步骤，后续评分无效"
4. 明确"最终分数 = 正式评分 - 扣分合计"的计算方式

v2.50 的问题：
- 扣分指令放在"第N步之前"，被淹没在大量评分标准中
- AI 按照既有评分锚定规则给分，忽略后加的扣分指令
- 问题创新性维度有效（曹俊金 40 分），但分析框架/结论维度无效

v2.50.1 的改进：
- 扣分指令放在 prompt 最前面，AI 先建立"检查负面模式"的思维框架
- 使用"⚠️ 如果跳过此步骤，后续评分无效"强制执行
- 明确"最终分数 = 正式评分 - 扣分合计"

预期改进：
- 曹俊金 < 60 分
- 邵莉莉 < 70 分
- 陈姿君 < 75 分"""

    # 2. 在三个维度的 prompt_template 开头注入扣分指令
    dimensions = config['dimensions']

    for dim in dimensions:
        if dim['key'] == 'problem_originality':
            original_start = "请对这篇法学论文的【问题创新性】进行评分"
            dim['prompt_template'] = PROBLEM_ORIGINALITY_PREFIX + dim['prompt_template']
            print(f"  ✅ 问题创新性：扣分指令前置")

        elif dim['key'] == 'analytical_framework':
            dim['prompt_template'] = ANALYTICAL_FRAMEWORK_PREFIX + dim['prompt_template']
            print(f"  ✅ 分析框架：扣分指令前置")

        elif dim['key'] == 'conclusion_consensus':
            dim['prompt_template'] = CONCLUSION_CONSENSUS_PREFIX + dim['prompt_template']
            print(f"  ✅ 结论可接受性：扣分指令前置")

    # 3. 保存
    with open(target_path, 'w', encoding='utf-8') as f:
        yaml.dump(config, f, allow_unicode=True, default_flow_style=False, sort_keys=False, width=1000)

    print(f"\n✅ 已生成 {target_path}")
    print(f"   - 基于 v2.47（推荐版本）")
    print(f"   - 扣分指令前置到 prompt 最前面")
    print(f"   - 强制先扣分后评分流程")


if __name__ == "__main__":
    apply_v2_50_1_rules()
